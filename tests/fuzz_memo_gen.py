#!/usr/bin/env python3
"""Generate random cases for tests/memo_compare.sh (same format as cases_perl.txt, no expected column).

usage: fuzz_memo_gen.py SEED COUNT > cases.txt

Only patterns the engine can memoize (no back references, lookarounds, atomic groups or bounded loops),
with nested unbounded loops, bodies that can be empty, lazy and possessive quantifiers and captures inside
loops.  Unlike fuzz_gen.py the results are never compared with Perl, so captures inside loops are fine.
"""
import random
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")

rnd = random.Random(int(sys.argv[1]))
COUNT = int(sys.argv[2])


def atom(depth):
    r = rnd.random()
    if depth <= 0 or r < 0.40:
        return rnd.choice(["a", "a", "b", "c", ".", "[ab]", "[^a]", r"\w", r"\b", "^", "$", "(?:)"])
    if r < 0.70:
        return "(" + alt(depth - 1) + ")"
    return "(?:" + alt(depth - 1) + ")"


def quant():
    return rnd.choice(["", "", "", "*", "+", "?", "*?", "+?", "??", "*+", "++", "{0,}", "{1,}", "{2,}"])


def piece(depth):
    return atom(depth) + quant()


def seq(depth):
    return "".join(piece(depth) for _ in range(rnd.randint(1, 3)))


def alt(depth):
    return "|".join(seq(depth) for _ in range(rnd.choice([1, 1, 2, 2, 3])))


def subject():
    return "".join(rnd.choice("aaabc") for _ in range(rnd.randint(0, 9)))


print("# generated by fuzz_memo_gen.py %s %s" % (sys.argv[1], sys.argv[2]))
for _ in range(COUNT):
    print("%s\t%s\t%s" % (rnd.choice(["", "", "g", "i", "m"]), alt(3), subject()))
