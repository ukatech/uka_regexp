#!/usr/bin/env python3
"""Generate random cases (same format as cases_perl.txt) for comparing the engine with Perl.

usage: fuzz_gen.py SEED COUNT [astral] > cases.txt

With "astral" the patterns and subjects also contain characters beyond the BMP (a surrogate pair
where wchar_t is 16 bit); the results are in code points, so they are the same for both sizes.

Capture groups are never generated inside a quantified construct because Perl resets such captures
on every iteration while this engine (like PCRE, .NET and Python) keeps the last value.
"""
import random
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")

rnd = random.Random(int(sys.argv[1]))
COUNT = int(sys.argv[2])
ASTRAL = len(sys.argv) > 3 and sys.argv[3] == "astral"
ASTRAL_CHARS = ["😀", "𐐀", "𐐨"]


def lit():
    if ASTRAL and rnd.random() < 0.3:
        return rnd.choice(ASTRAL_CHARS)
    return rnd.choice("abc")


class Gen:
    def __init__(self, multiline):
        self.groups = 0
        self.closed = []
        self.multiline = multiline

    def atom_simple(self):
        r = rnd.random()
        if r < 0.45:
            return lit()
        if r < 0.55:
            return "."
        if r < 0.65:
            if ASTRAL and rnd.random() < 0.3:
                return rnd.choice(["[😀a]", "[^😀]", "[😀-🙏]", "[^a𐐀]"])
            return rnd.choice(["[ab]", "[^a]", "[a-c]", "[^bc]", "[b ]"])
        if r < 0.75:
            return rnd.choice(["\\w", "\\W", "\\d", "\\s", "\\D", "\\S", "\\N", "\\R", "\\h", "\\H"])
        if r < 0.80:
            return rnd.choice(["\\b", "\\B", "\\A", "\\z", "\\Z", "^", "$", "\\v", "\\V"])
        return lit()

    def quant(self):
        r = rnd.random()
        if r < 0.35:
            return ""
        q = rnd.choice(["*", "+", "?", "{2}", "{1,2}", "{2,}", "{0,2}", "{1,3}"])
        s = rnd.random()
        if s < 0.2:
            q += "?"
        elif s < 0.3:
            q += "+"
        return q

    def seq(self, depth, allow_cap, in_look=False):
        n = rnd.choice([1, 1, 2, 2, 3, 4])
        parts = []
        for _ in range(n):
            parts.append(self.item(depth, allow_cap, in_look))
        return "".join(parts)

    def alt(self, depth, allow_cap, in_look=False):
        n = rnd.choice([1, 1, 1, 2, 2, 3])
        return "|".join(self.seq(depth, allow_cap, in_look) for _ in range(n))

    def item(self, depth, allow_cap, in_look):
        r = rnd.random()
        if depth >= 3 or r < 0.55:
            a = self.atom_simple()
            if a in ("\\b", "\\B", "\\A", "\\z", "^", "$"):
                return a
            return a + (self.quant() if not in_look else rnd.choice(["", "", "?"]))
        q = self.quant() if not in_look else ""
        cap_ok = allow_cap and q == ""
        kind = rnd.random()
        if kind < 0.28 and cap_ok:
            self.groups += 1
            idx = self.groups
            body = self.alt(depth + 1, cap_ok, in_look)
            self.closed.append(idx)
            return "(" + body + ")" + q
        if kind < 0.45:
            return "(?:" + self.alt(depth + 1, cap_ok, in_look) + ")" + q
        if kind < 0.52:
            return "(?>" + self.alt(depth + 1, cap_ok, in_look) + ")" + q
        if kind < 0.58:
            return "(?i:" + self.alt(depth + 1, cap_ok, in_look) + ")" + q
        if kind < 0.68:
            return rnd.choice(["(?=", "(?!"]) + self.alt(depth + 1, cap_ok and q == "", True) + ")"
        if kind < 0.78:
            body = "|".join("".join(rnd.choice(["a", "b", "c", "[ab]", ".", "\\w"]) + rnd.choice(["", "", "", "{1,2}"])
                                    for _ in range(rnd.choice([1, 2]))) for _ in range(rnd.choice([1, 1, 2])))
            return rnd.choice(["(?<=", "(?<!"]) + body + ")"
        if kind < 0.88 and self.closed:
            g = rnd.choice(self.closed)
            return "\\%d" % g + (self.quant() if not in_look else "")
        if kind < 0.94 and self.closed:
            g = rnd.choice(self.closed)
            return "(?(%d)%s|%s)" % (g, self.seq(depth + 1, False, in_look), self.seq(depth + 1, False, in_look))
        return "(?:" + self.alt(depth + 1, cap_ok, in_look) + ")" + q


def subject(multiline):
    n = rnd.choice([0, 1, 2, 3, 4, 5, 6, 7, 8])
    alphabet = "aabbc 1A\n"
    s = "".join(rnd.choice(alphabet) for _ in range(n))
    if ASTRAL:
        s = "".join(c if rnd.random() < 0.7 else rnd.choice(ASTRAL_CHARS) for c in s)
    return s.replace("\n", "\\n")


print("# generated by fuzz_gen.py %s %s" % (sys.argv[1], sys.argv[2]))
for _ in range(COUNT):
    ml = rnd.random() < 0.2
    g = Gen(ml)
    pat = g.alt(0, True)
    flags = ""
    if ml:
        flags += "m"
    if rnd.random() < 0.2:
        flags += "i"
    if rnd.random() < 0.15:
        flags += "s"
    if rnd.random() < 0.2:
        flags += "g"
    print("%s\t%s\t%s" % (flags, pat, subject(ml)))
